"""Generate the fixed C declarations/metadata from the published precode.

Run explicitly when changing this NEW implementation; CMake does not regenerate
files or read private work. This is not a SOURCE producer or a model generator.
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
SCHEMA = HERE.parents[1] / "docs/schemas/owned-source-writer-c-abi-v1"
LAY = json.loads((SCHEMA / "docs-proposals/pod-layouts-final-proposed.json").read_text())
CON = json.loads((SCHEMA / "contract-final-proposed.json").read_text())
MEM = json.loads((SCHEMA / "docs-proposals/private-memory-final-proposed.json").read_text())
EVENTS = json.loads((SCHEMA / "docs-proposals/source-callbacks-final-proposed.json").read_text())["events"]
TYPES = LAY["layouts"]


def declaration(ctype, name):
    if "[" in ctype:
        base, tail = ctype.split("[", 1)
        return base + " " + name + "[" + tail
    return ctype + " " + name


out = ["/* Generated by generate_owned_source_writer.py; published V1 layouts. */",
       "#ifndef D4VR_OWNED_SOURCE_WRITER_SOURCE_V1_H", "#define D4VR_OWNED_SOURCE_WRITER_SOURCE_V1_H",
       "#include <stdint.h>", "#include <stddef.h>", "#include <string.h>",
       "#if defined(__cplusplus)", "#define OSW_ASSERT(c,m) static_assert(c,m)",
       "#define OSW_ALIGNOF(t) alignof(t)", 'extern "C" {', "#else",
       "#define OSW_ASSERT(c,m) _Static_assert(c,m)", "#define OSW_ALIGNOF(t) _Alignof(t)", "#endif",
       "#define OSW_BIT(n) (UINT64_C(1) << (n))", "#define OSW_BITS(n) ((UINT64_C(1) << (n)) - UINT64_C(1))"]
for group, values in CON["C_ABI"]["enum_tables"].items():
    for name, number in values.items():
        out.append(f"#define OSW_{group.upper()}_{name.upper()} {number}u")
for name, number in CON["C_ABI"]["status_values"].items():
    out.append(f"#define OSW_{name} {number}u")

done = set()


def emit(key):
    if key in done:
        return
    t = TYPES[key]
    for f in t.get("fields", []):
        dep = f.get("layout", f.get("element_layout"))
        if dep:
            emit(dep)
    for dep in t.get("alternatives", []):
        emit(dep)
    name = t["C_name"]
    if "C_storage" in t:
        out.append(f"typedef {t['C_storage']} {name};")
    else:
        kind = "union" if "alternatives" in t else "struct"
        out.append(f"typedef {kind} {name} {{")
        for dep in t.get("alternatives", []):
            out.append(f"    {TYPES[dep]['C_name']} as_{dep.lower()};")
        for f in t.get("fields", []):
            out.append("    " + declaration(f["C_type"], f["name"]) + ";")
        out.append(f"}} {name};")
    out.append(f'OSW_ASSERT(sizeof({name}) == {t["sizeof_PROPOSED"]}, "{key} size");')
    out.append(f'OSW_ASSERT(OSW_ALIGNOF({name}) == {t["alignof_PROPOSED"]}, "{key} alignment");')
    for f in t.get("fields", []):
        out.append(f'OSW_ASSERT(offsetof({name}, {f["name"]}) == {f["offset"]}, "{key}.{f["name"]}");')
        if "mask_bit" in f:
            out.append(f'#define OSW_{key.upper()}_{f["name"].upper()}_BIT {f["mask_bit"]}u')
    if "fields" in t:
        out.append(f"static inline void osw_init_{key.lower()}_v1({name} *p) {{")
        out.append("    memset(p, 0, sizeof(*p));")
        if key.startswith(("Before_", "After_")):
            out.extend(["    p->abi_size = (uint32_t)sizeof(*p);", "    p->abi_version = 1u;"])
        out.append("}")
    done.add(key)


for k in TYPES:
    emit(k)
out += ["/* Private SOURCE calls; none are APP control exports. */", CON["source_API"]["entry_signature"]]
for e in EVENTS:
    for field in ["before_commit", "after", "observer"]:
        if e.get(field):
            out.append(e[field])
for field in ["constructor_note_signature", "constructor_note_current_signature", "return_admit_signature", "drain_return_signature"]:
    out.append(CON["source_API"][field])
out.append("/* Six new metadata controls: uint32 status, never original HRESULT. */")
out.extend(c["signature"] for c in CON["ownership_and_controls"]["controls"])
# Public status has a separately normative private-memory layout.
status = MEM["layouts"]["PublicStatus"]
at = out.index(next(x for x in out if x.startswith("/* Private SOURCE")))
statuslines = ["typedef struct osw_status_v1 {"]
statuslines += ["    " + declaration(f["C_type"], f["name"]) + ";" for f in status["fields"]]
statuslines += ["} osw_status_v1;", 'OSW_ASSERT(sizeof(osw_status_v1)==192, "status size");']
statuslines.append('OSW_ASSERT(OSW_ALIGNOF(osw_status_v1)==8, "status alignment");')
statuslines.extend(f'OSW_ASSERT(offsetof(osw_status_v1,{f["name"]})=={f["offset"]}, "status.{f["name"]}");' for f in status["fields"])
out[at:at] = statuslines
out += ["#if defined(OSW_CPU_TESTING)", "/* At most two private CPU contexts; absent from production. */",
        "uint32_t d4vr_osw_test_select_context_v1(uint32_t index);",
        "uint32_t d4vr_osw_test_recreate_context_v1(uint32_t index);", "#endif",
        "#if defined(__cplusplus)", "}", "#endif", "#endif"]
(HERE / "owned_source_writer_source_v1.h").write_text("\n".join(out) + "\n")

# Read-only descriptors are compiled constants, never another mutable capture
# arena. They describe only the fixed C PODs, not arbitrary user addresses.
keys = list(TYPES)
ids = {key: i for i, key in enumerate(keys)}
wire = json.loads((SCHEMA.parent / "owned-source-writer-v1.json").read_text())
meta = ["/* Generated fixed reflection; no runtime schema/AST allocation. */"]
for k, t in TYPES.items():
    if not t.get("mask_field_count"):
        continue
    fields = []
    grammar = wire["types"].get(k)
    if k.startswith("Args_"):
        grammar = wire["callback_catalog"][k[5:]]["args"]
    elif k.startswith("Result_"):
        grammar = wire["callback_catalog"][k[7:]]["result"]
    for f in t["fields"]:
        if "mask_bit" not in f:
            continue
        name = f.get("wire_key", f["name"])
        desc = grammar.get(name, "") if isinstance(grammar, dict) else ""
        nullable = "null" in desc.lower() if isinstance(desc, str) else False
        if k in ["SourceEntryInput", "SourceAfterInput"]:
            nullable = True
        fields.append(f'    {{"{name}", {f["offset"]}u, {ids[f["layout"]]}u, {f["mask_bit"]}u, {int(nullable)}u}},')
    meta.append(f"static const osw_field_desc fields_{ids[k]}[] = {{\n" + "\n".join(fields) + "\n};")
meta.append("static const osw_type_desc type_desc[] = {")
for k, t in TYPES.items():
    kind = {"U16": "T_U16", "U32": "T_U32", "Bool": "T_BOOL", "I32": "T_I32", "Enum32": "T_I32", "U64": "T_U64", "ID": "T_U64", "String": "T_STRING", "SHA256": "T_SHA", "GUID": "T_GUID", "Nonce32": "T_NONCE"}.get(k)
    elem = cap = 0
    if not kind:
        if "array_capacity" in t:
            kind = "T_ARRAY"
            f = next(f for f in t["fields"] if "element_layout" in f)
            elem, cap = ids[f["element_layout"]], f["count_cap"]
        elif t.get("mask_field_count"):
            kind = "T_OBJECT"
        else:
            kind = "T_UNION"
    mask = t.get("mask_field_count", 0)
    fs = f"fields_{ids[k]}" if mask else "NULL"
    meta.append(f'    {{"{k}", {kind}, {t["sizeof_PROPOSED"]}u, {elem}u, {cap}u, {mask}u, {fs}}},')
meta.append("};")
for k in keys:
    meta.append(f"#define TYPE_{k.upper()} {ids[k]}u")
meta.append("static const osw_event_desc event_desc[47] = { {0},")
for e in EVENTS:
    api = e["api"]
    after = TYPES["After_" + api]
    so = next(f["offset"] for f in after["fields"] if f["name"] == "source_after")
    result_void = e["result_wire_mapping"] is None
    meta.append(f'    {{"{api}", "{e["domain"]}", {ids["Args_"+api]}u, {ids["Result_"+api]}u, {TYPES["Before_"+api]["sizeof_PROPOSED"]}u, {after["sizeof_PROPOSED"]}u, {so}u, {int(result_void)}u}},')
meta.append("};")
for group in ["object_kind", "source_site", "pipeline_route", "device_origin", "scopegap_code", "pipeline_next_kind"]:
    vals = CON["C_ABI"]["enum_tables"][group]
    meta.append(f"static const char *const enum_{group}[] = {{NULL, " + ", ".join(json.dumps(x) for x in vals) + "};")
(HERE / "owned_source_writer_metadata.inc").write_text("\n".join(meta) + "\n")

private = ["/* Generated typed private arena declarations, not APP ABI. */"]
for key in ["Pending", "Identity", "ContextHeader", "CoreIssuer"]:
    t = MEM["layouts"][key]
    private.append(f"typedef struct {t['C_name']} {{")
    private.extend("    " + declaration(f["C_type"], f["name"]) + ";" for f in t["fields"])
    private.append(f"}} {t['C_name']};")
    private.append(f'OSW_ASSERT(sizeof({t["C_name"]})=={t["sizeof_PROPOSED"]}, "{key} size");')
    private.append(f'OSW_ASSERT(OSW_ALIGNOF({t["C_name"]})=={t["alignof_PROPOSED"]}, "{key} alignment");')
    for f in t["fields"]:
        private.append(f'OSW_ASSERT(offsetof({t["C_name"]}, {f["name"]})=={f["offset"]}, "{key}.{f["name"]}");')
(HERE / "owned_source_writer_private.inc").write_text("\n".join(private) + "\n")
wrappers = ["/* Generated exact SOURCE forwarding-to-sink declarations. */"]
for e in EVENTS:
    a = e["api"]
    stem = a.lower()
    if a == "ScopeGap":
        continue
    wrappers.append(e["before_commit"][:-1] + f" {{ return before_commit({e['tag']}u, token, before); }}")
    if a == "Release":
        wrappers.append(e["after"][:-1] + f" {{ osw_after_release_v1 p; osw_init_after_release_v1(&p); p.result.observed_mask=1; p.result.present_mask=1; p.result.value=actual_ulong; return after_return({e['tag']}u, token, &p); }}")
    elif e["result_wire_mapping"] is None:
        wrappers.append(e["after"][:-1] + f" {{ return after_return({e['tag']}u, token, NULL); }}")
    else:
        wrappers.append(e["after"][:-1] + f" {{ return after_return({e['tag']}u, token, after); }}")
(HERE / "owned_source_writer_callbacks.inc").write_text("\n".join(wrappers) + "\n")
