class FakePipe:
    """Ordinary Python test double: no FD, pipe, child or system call exists."""
    def __init__(self, number):
        self.number = number
        self.close_count = 0

    def fileno(self):
        return self.number

    def close(self):
        self.close_count += 1


class FakeProcess:
    def __init__(self, returncode=23):
        self.stdout = FakePipe(100)
        self.stderr = FakePipe(101)
        self.returncode = returncode
        self.wait_count = 0
        self.poll_count = 0

    def poll(self):
        self.poll_count += 1
        return self.returncode

    def wait(self):
        self.wait_count += 1
        return self.returncode


def enrich_original_journal(cap, address_offset=0):
    """Add declared CPU-only auxiliaries using independent original creations.

    The original receipt strings stay byte-exact. APP IDs/clocks are scaled
    coherently, without interpreting or replacing SOURCE generations/clocks.
    """
    def scale(value):
        if type(value) is dict:
            if set(value) == {'ordinal', 'entry', 'return'}:
                return {key: number * 100 for key, number in value.items()}
            result = {key: scale(child) for key, child in value.items()}
            if {'ordinal', 'transition', 'edge', 'api'} <= set(value):
                result['ordinal'] *= 100
                result['transition'] *= 100
            return result
        if type(value) is list: return [scale(child) for child in value]
        return value
    cap.envelope = scale(cap.envelope)
    cap.journal = scale(cap.journal)
    cap.child = scale(cap.child)
    events = cap.journal['events']
    device = next(row['result']['output'] for row in events
                  if row['api'] == 'D3D12CreateDevice' and row['edge'] == 'after')
    refs = {role: dict(raw=70000 + address_offset + i, generation=100 + i)
            for i, role in enumerate(('root', 'pipeline', 'target'), 1)}
    def add(ordinal, entry, api, kind, args, result, case=0):
        common = dict(ordinal=ordinal, api=api, case_ordinal=case, return_kind=kind, args=args)
        events.extend((dict(common, transition=entry, edge='before', original_returned=False, result=None),
                       dict(common, transition=entry + 1, edge='after', original_returned=True, result=result)))
    reset = next(row for row in events if row['api'] == 'Reset' and row['edge'] == 'before' and row['case_ordinal'] == 1)
    blob = dict(raw=72000 + address_offset, generation=150)
    blob_pointer = 0x100000 + address_offset
    add(reset['ordinal'] - 6, reset['transition'] - 15, 'D3D12SerializeRootSignature', 'HRESULT',
        dict(version=1, parameter_count=3, flags=1, description_pointer=50000 + address_offset,
             blob_output_pointer=51000 + address_offset, error_output_pointer=52000 + address_offset),
        dict(hresult=0, output=dict(root_blob=blob, error_blob=None)))
    add(reset['ordinal'] - 5, reset['transition'] - 13, 'GetBufferPointer', 'pointer',
        dict(blob=blob), dict(value=blob_pointer))
    add(reset['ordinal'] - 4, reset['transition'] - 11, 'GetBufferSize', 'uint64',
        dict(blob=blob), dict(value=144))
    for i, (role, api) in enumerate((('root', 'CreateRootSignature'), ('pipeline', 'CreateGraphicsPipelineState'), ('target', 'CreateCommittedResource'))):
        args = dict(device=device, purpose='CPU declared auxiliary ' + role)
        if role == 'root': args.update(blob=blob, blob_data_pointer=blob_pointer, blob_bytes=144)
        if role == 'target':
            args['description'] = dict(dimension=3, width=256, height=144, depth_or_array_size=1,
                mip_levels=1, format=87, sample_count=1, flags=1)
        add(reset['ordinal'] - 3 + i, reset['transition'] - 9 + 2 * i,
            api, 'HRESULT', args, dict(hresult=0, output=refs[role]))
    for case in (1, 2):
        reset_after = next(row for row in events if row['api'] == 'Reset' and row['edge'] == 'after' and row['case_ordinal'] == case)
        add(reset_after['ordinal'] + 1, reset_after['transition'] + 1, 'SetPipelineState', 'void',
            dict(pipeline=refs['pipeline']['raw']), None, case)
        bind = next(row for row in events if row['api'] == 'SetDescriptorHeaps' and row['edge'] == 'before' and row['case_ordinal'] == case)
        add(bind['ordinal'] - 1, bind['transition'] - 2, 'SetGraphicsRootSignature', 'void',
            dict(root=refs['root']['raw']), None, case)
        close = next(row for row in events if row['api'] == 'Close' and row['edge'] == 'before' and row['case_ordinal'] == case)
        readback = next(row['result']['output'] for row in events if row['api'] == 'CreateCommittedResource'
                        and row['edge'] == 'after' and row['ordinal'] == cap.envelope['cases'][0]['object_calls']['readback']['ordinal'])
        add(close['ordinal'] - 1, close['transition'] - 2, 'CopyTextureRegion', 'void',
            dict(source=refs['target']['raw'], destination=readback), None, case)
    events.sort(key=lambda row: row['transition'])
    cap.write()


class RuntimeExecutionTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory(prefix='private-owned-execution-')
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name).resolve()
        p = patch.object(subprocess, 'Popen', side_effect=AssertionError('No process in CPU tests'))
        p.start(); self.addCleanup(p.stop)

    def denied(self, cap):
        try:
            result = cap.audit()
        except ValueError:
            return
        self.assertFalse(result['supplied_files_consistent'])

    def test_new_mock_file_inputs_keep_full_pure_result_and_no_runtime_attestation(self):
        cap = Capture(self.root)
        real = execution.analyze
        with patch.object(execution, 'analyze', wraps=real) as probe:
            report = cap.audit()
        self.assertEqual(probe.call_count, 1)
        self.assertTrue(report['supplied_files_consistent'])
        self.assertFalse(report['execution_declared'])
        self.assertEqual(report['claims'], {key: False for key in FALSE_CLAIMS})
        self.assertEqual(report['supplied_relation_audit'], real((cap.directory / 'output/envelope.json').read_bytes()))
        self.assertTrue(report['supplied_relation_audit']['supplied_outer_copy_and_APP_argument_relation_known'])

    def test_two_distinct_run_nonces_preserve_same_four_images_and_original_schedule(self):
        off = Capture(self.root, 'off'); on = Capture(self.root, 'on')
        pins = dict(schema_version=1, purpose='private_translator_runtime_pair_pins', runs=dict(off=off.pins, on=on.pins))
        report = execution.audit_pair(str(self.root), pins)
        self.assertTrue(report['supplied_pair_files_consistent'])
        self.assertEqual((report['readbacks'], report['readback_bytes']), (4, 589824))
        self.assertFalse(report['runs']['off']['supplied_relation_audit']['supplied_outer_copy_and_APP_argument_relation_known'])

    def test_pair_joins_root_pipeline_and_texture_copy_by_actual_creation_roles(self):
        off = Capture(self.root, 'off'); on = Capture(self.root, 'on')
        enrich_original_journal(off, 1000); enrich_original_journal(on, 2000)
        pins = dict(schema_version=1, purpose='private_translator_runtime_pair_pins', runs=dict(off=off.pins, on=on.pins))
        report = execution.audit_pair(str(self.root), pins)
        self.assertTrue(report['supplied_pair_files_consistent'])
        self.assertTrue(report['captured_original_argument_roles_and_HRESULTs_equal'])
        # A raw root value which was never an original creation output cannot
        # be excused as an unknown pointer or matched by first occurrence.
        for row in on.journal['events']:
            if row['api'] == 'SetGraphicsRootSignature': row['args']['root'] = 999999
        on.write(); pins['runs']['on'] = on.pins
        with self.assertRaises(ValueError): execution.audit_pair(str(self.root), pins)

    def test_pair_refuses_changed_auxiliary_original_arguments(self):
        off = Capture(self.root, 'off'); on = Capture(self.root, 'on')
        enrich_original_journal(off, 1000); enrich_original_journal(on, 2000)
        for row in on.journal['events']:
            if row['api'] == 'CopyTextureRegion': row['args']['destination'] = row['args']['source']
        on.write()
        pins = dict(schema_version=1, purpose='private_translator_runtime_pair_pins', runs=dict(off=off.pins, on=on.pins))
        with self.assertRaises(ValueError): execution.audit_pair(str(self.root), pins)

    def test_original_blob_pointer_return_is_strict_U64_not_truthiness(self):
        cap = Capture(self.root)
