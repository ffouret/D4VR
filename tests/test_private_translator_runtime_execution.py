def digest(raw):
    return hashlib.sha256(raw).hexdigest()


def encoded(value):
    return json.dumps(value, ensure_ascii=True, allow_nan=False, separators=(',', ':')).encode('ascii')


def pixels(second):
    result = bytearray()
    for y in range(144):
        ty = min(7, max(0, (2 * y + 1 - 36) // 36))
        for x in range(256):
            tx = min(7, max(0, (2 * x + 1 + 64) // 64))
            rgba = ((233 - 11 * tx, 211 - 17 * ty, 197 - 5 * tx - 9 * ty, 83 + 7 * tx + 11 * ty)
                    if second else (17 + 13 * tx, 29 + 19 * ty, 41 + 7 * tx + 11 * ty, 255))
            result.extend((rgba[2], rgba[1], rgba[0], rgba[3]))
    return bytes(result)


