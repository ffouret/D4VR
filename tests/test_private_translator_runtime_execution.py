    def test_regular_file_reader_refuses_growth_and_permission_failure(self):
        file = self.root / 'owned.bin'; file.write_bytes(b'abcdef')
        real = execution.os.read; changed = False
        def growing(fd, size):
            nonlocal changed
            result = real(fd, size)
            if not changed:
                changed = True
                with file.open('ab') as stream: stream.write(b'X')
            return result
        with patch.object(execution.os, 'read', side_effect=growing):
            with self.assertRaises(ValueError): execution.read_regular(str(file), 6)
        if os.name != 'nt':
            with patch.object(execution.os, 'open', side_effect=PermissionError('owned denial')):
                with self.assertRaises(ValueError): execution.read_regular(str(file), 10)

    def test_regular_file_size_limit_and_symlink_artifact_are_not_bypassed(self):
        file = self.root / 'owned.bin'; file.write_bytes(b'abcdef')
        self.assertEqual(execution.read_regular(str(file), 6), b'abcdef')
        with self.assertRaises(ValueError): execution.read_regular(str(file), 5)
        cap = Capture(self.root)
